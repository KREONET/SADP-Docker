<?php

use App\Models\InstanceSettings;
use App\Models\Team;
use App\Models\User;
use Database\Seeders\RootUserSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Process;

uses(RefreshDatabase::class);

const ROOT_USER_ENV_KEYS = ['ROOT_USERNAME', 'ROOT_USER_EMAIL', 'ROOT_USER_PASSWORD'];

beforeEach(function () {
    Http::fake(['api.pwnedpasswords.com/*' => Http::response('')]);
    Team::factory()->create(['id' => 0, 'name' => 'Root Team']);
    InstanceSettings::forceCreate(['id' => 0, 'is_registration_enabled' => true]);
});

afterEach(function () {
    foreach (ROOT_USER_ENV_KEYS as $key) {
        unset($_ENV[$key], $_SERVER[$key]);
    }
});

function setRootUserEnvironment(string $username, string $email, string $password): void
{
    foreach (array_combine(ROOT_USER_ENV_KEYS, [$username, $email, $password]) as $key => $value) {
        $_ENV[$key] = $value;
        $_SERVER[$key] = $value;
    }
}

function runRootUserSeeder(): void
{
    ob_start();
    (new RootUserSeeder)->run();
    ob_end_clean();
}

it('creates the installer root account on an internal domain and disables registration', function () {
    setRootUserEnvironment('root', 'root@paded.local', 'Q7mWx2KpLr9TzVb4NcHdAa1_');

    runRootUserSeeder();

    $root = User::find(0);
    expect($root)->not->toBeNull()
        ->and($root->email)->toBe('root@paded.local')
        ->and($root->teams()->whereKey(0)->first()?->pivot?->role)->toBe('owner')
        ->and(InstanceSettings::find(0)->is_registration_enabled)->toBeFalse();
});

it('accepts the random root password generated by the installer', function () {
    $password = trim(Process::run("openssl rand -base64 32 | tr -dc 'A-Za-z0-9' | head -c 20")->output()).'Aa1_';
    setRootUserEnvironment('root', 'root@paded.local', $password);

    runRootUserSeeder();

    expect(User::find(0))->not->toBeNull();
});

it('does not create the root account with a weak password', function () {
    setRootUserEnvironment('root', 'root@paded.local', 'password');

    runRootUserSeeder();

    expect(User::find(0))->toBeNull()
        ->and(InstanceSettings::find(0)->is_registration_enabled)->toBeTrue();
});
